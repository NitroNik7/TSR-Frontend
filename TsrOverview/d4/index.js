function createDialog(isImg, src) {
    let dialog = document.createElement("dialog");
    dialog.id = "tsrImageViewer";
    dialog.classList.add("border");

    let closeDiv = document.createElement("div");
    let closeBtn = document.createElement("button");
    closeBtn.classList.add("btn-close");
    closeBtn.onclick = closeDialog;

    closeDiv.setAttribute("align", "right");
    closeDiv.appendChild(closeBtn);

    let contentDiv = document.createElement("div");
    contentDiv.style.overflowX = "auto";

    if (isImg) {
        let img = document.createElement("img");
        img.classList.add("m-3")
        img.src = src;
        contentDiv.appendChild(img);
    } else {
        contentDiv.innerHTML = src;
    }

    dialog.appendChild(closeDiv);
    dialog.appendChild(contentDiv);

    document.body.appendChild(dialog);

    dialog.showModal();

    document.addEventListener("keydown", handleKeydown);
}

function handleKeydown(e) {
    if (e.key === "Escape") {
        closeDialog();
    }
}

function closeDialog() {
    let dialog = document.getElementById("tsrImageViewer");
    dialog.close();
    document.body.removeChild(dialog);

    document.removeEventListener("keydown", handleKeydown);
}


